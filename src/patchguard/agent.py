"""PatchGuard AI-Native Coding Agent (built from scratch, no frameworks).

=============================================================================
WHY THIS MODULE EXISTS (Agentic ReAct Loop & HITL Concept):
This is the central brain of PatchGuard. It implements an autonomous ReAct
(Reason + Act) loop from first principles without external agent frameworks.

How the Agentic Execution Cycle Works:
1. Context Engineering: Formulates system prompt instructing the agent on
   methodical diagnosis, surgical patching, and verification rules.
2. Step Cap Check: Pre-step check against the maximum allowed steps limit.
3. LLM Query: Submits conversation history and available MCP tool schemas to LLM.
4. Token & Cost Governance: Parses tokens used and updates financial/token monitor.
5. Tool Dispatch: If model generates tool calls:
   a. Pre-execution PathGuard validation (blocks unauthorized traversal immediately).
   b. Human-In-The-Loop (HITL) approval hook: Prompts the human operator for
      confirmation before executing mutating tools (write_file, edit_file, docker).
   c. MCP Execution: Invokes tool on MCP server over stdio and appends output.
6. Termination: Loops until the model determines the task is complete, or halts
   safely if any structural governance threshold is breached.
=============================================================================
"""

from __future__ import annotations

import asyncio
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Optional

from patchguard.guardrails import (
    GovernanceConfig,
    PathGuard,
    SafetyMonitor,
    SafetyViolation,
    SafetyViolationType,
)
from patchguard.llm import (
    BaseLLMProvider,
    LLMMessage,
    LLMResponse,
    ToolCall,
)
from patchguard.mcp_client import PatchGuardMCPClient

# System prompt engineered for systematic, disciplined engineering behavior
SYSTEM_PROMPT = """You are PatchGuard, an elite AI-native autonomous software engineering agent.
Your mission is to systematically diagnose repository bugs, apply minimal and surgical fixes,
and verify your solution using Docker-sandboxed test runs under structural governance.

Rules of Engagement:
1. DIAGNOSE FIRST: Read source files or run sandboxed tests to understand the exact failure mechanism before editing code.
2. SURGICAL FIX: Make minimal, high-precision modifications using `edit_file` or `write_file`.
3. VERIFY VIA SANDBOX: Always run `run_docker_tests` to verify that existing tests pass and no regressions are introduced.
4. STRUCTURAL GOVERNANCE:
   - Stay within allowed repository paths. Attempts to traverse directories (`..`) or touch protected files (.git, .env) will be blocked.
   - Be concise and efficient: you are operating under strict step caps and token budgets.
5. CONCLUDE: When all tests pass and the task is solved, provide a clear diagnostic summary and the patch details.
"""


@dataclass
class AgentRunResult:
    """Outcome and tracked telemetry of an agent execution.

    Attributes:
        status: High-level status ('SUCCESS', 'STEP_CAP_EXCEEDED', 'TOKEN_BUDGET_EXCEEDED', etc.)
        summary: Final diagnostic explanation or conclusion from the agent.
        steps_taken: How many tool cycles were executed.
        prompt_tokens: Cumulative input tokens sent to LLM.
        completion_tokens: Cumulative output tokens generated by LLM.
        total_tokens: Total token consumption.
        cost_usd: Estimated financial cost in USD.
        violations: List of security/governance violations intercepted during run.
        test_passed: Whether the verification tests passed inside the sandbox.
        git_diff: Uncommitted code modifications produced by the agent.
        messages: Full conversation history of messages and tool calls.
    """

    status: str
    summary: str
    steps_taken: int
    prompt_tokens: int
    completion_tokens: int
    total_tokens: int
    cost_usd: float
    violations: list[dict[str, Any]] = field(default_factory=list)
    test_passed: bool = False
    git_diff: str = ""
    messages: list[dict[str, Any]] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """Convert result to dictionary for reporting and JSON serialization."""
        return {
            "status": self.status,
            "summary": self.summary,
            "steps_taken": self.steps_taken,
            "prompt_tokens": self.prompt_tokens,
            "completion_tokens": self.completion_tokens,
            "total_tokens": self.total_tokens,
            "cost_usd": self.cost_usd,
            "violations_count": len(self.violations),
            "violations": self.violations,
            "test_passed": self.test_passed,
            "git_diff": self.git_diff,
        }


def default_human_approval_hook(tool_name: str, arguments: dict[str, Any]) -> bool:
    """Default interactive CLI prompt for human-in-the-loop (HITL) approval.

    Read-only operations (read_file, list_dir, search_code) proceed automatically.
    Mutating or external operations (write_file, edit_file, run_docker_tests) pause
    and prompt the operator for confirmation.
    """
    mutating_tools = {"write_file", "edit_file", "run_docker_tests"}
    if tool_name not in mutating_tools:
        return True

    print(f"\n[PatchGuard HITL Approval Required]")
    print(f"Tool: {tool_name}")
    print(f"Arguments: {arguments}")
    try:
        response = input("Approve tool execution? [Y/n]: ").strip().lower()
        return response in ("", "y", "yes")
    except EOFError:
        return True


class PatchGuardAgent:
    """Autonomous coding agent with structural governance and MCP tool orchestration."""

    def __init__(
        self,
        llm: BaseLLMProvider,
        repo_root: str | Path,
        governance: GovernanceConfig | None = None,
        approval_hook: Optional[Callable[[str, dict[str, Any]], bool]] = None,
        mcp_client: Optional[PatchGuardMCPClient] = None,
    ) -> None:
        self.llm = llm
        self.repo_root = Path(repo_root).resolve()
        self.governance = governance or GovernanceConfig()
        self.approval_hook = approval_hook or default_human_approval_hook
        self.mcp_client = mcp_client or PatchGuardMCPClient(repo_root=self.repo_root)

        # Initialize PathGuard for pre-execution path validation
        self.path_guard = PathGuard(
            repo_root=self.repo_root,
            path_allowlist=self.governance.path_allowlist,
            protected_patterns=self.governance.protected_patterns,
        )

        # Initialize SafetyMonitor for step cap, token budget, and cost enforcement
        self.monitor = SafetyMonitor(self.governance)

    async def run(self, task_description: str) -> AgentRunResult:
        """Execute autonomous agent loop on the given coding task."""
        # Seed conversation history with system instructions and user task
        messages: list[LLMMessage] = [
            LLMMessage(role="system", content=SYSTEM_PROMPT),
            LLMMessage(role="user", content=f"Task: {task_description}"),
        ]

        # Connect to MCP server subprocess over stdio
        async with self.mcp_client as client:
            tools = await client.list_tools()

            test_passed = False
            last_assistant_text = ""

            # --- Autonomous ReAct Loop ---
            while True:
                # STEP 1: Enforce Step Cap
                try:
                    self.monitor.record_step()
                except SafetyViolation as sv:
                    # Halt safely if agent exceeds step cap
                    diff = await client.call_tool("git_diff", {})
                    return AgentRunResult(
                        status="STEP_CAP_EXCEEDED",
                        summary=f"Halted: {sv.message}",
                        steps_taken=self.monitor.current_step,
                        prompt_tokens=self.monitor.prompt_tokens,
                        completion_tokens=self.monitor.completion_tokens,
                        total_tokens=self.monitor.total_tokens,
                        cost_usd=self.monitor.cost_usd,
                        violations=[v.to_dict() for v in self.monitor.violations],
                        test_passed=test_passed,
                        git_diff=diff,
                        messages=[m.to_dict() for m in messages],
                    )

                # STEP 2: Query LLM with conversation history and available MCP tools
                try:
                    llm_response: LLMResponse = self.llm.complete(
                        messages=messages,
                        tools=tools,
                    )
                except Exception as exc:
                    return AgentRunResult(
                        status="ERROR",
                        summary=f"LLM completion error: {exc}",
                        steps_taken=self.monitor.current_step,
                        prompt_tokens=self.monitor.prompt_tokens,
                        completion_tokens=self.monitor.completion_tokens,
                        total_tokens=self.monitor.total_tokens,
                        cost_usd=self.monitor.cost_usd,
                        violations=[v.to_dict() for v in self.monitor.violations],
                        test_passed=test_passed,
                        messages=[m.to_dict() for m in messages],
                    )

                # STEP 3: Track token and financial expenditure, enforcing budgets
                try:
                    self.monitor.record_usage(
                        prompt_tokens=llm_response.prompt_tokens,
                        completion_tokens=llm_response.completion_tokens,
                        estimated_cost=llm_response.cost_usd,
                    )
                except SafetyViolation as sv:
                    # Halt safely if token budget or dollar limit is exceeded
                    diff = await client.call_tool("git_diff", {})
                    return AgentRunResult(
                        status="TOKEN_BUDGET_EXCEEDED",
                        summary=f"Halted: {sv.message}",
                        steps_taken=self.monitor.current_step,
                        prompt_tokens=self.monitor.prompt_tokens,
                        completion_tokens=self.monitor.completion_tokens,
                        total_tokens=self.monitor.total_tokens,
                        cost_usd=self.monitor.cost_usd,
                        violations=[v.to_dict() for v in self.monitor.violations],
                        test_passed=test_passed,
                        git_diff=diff,
                        messages=[m.to_dict() for m in messages],
                    )

                last_assistant_text = llm_response.content or ""
                messages.append(
                    LLMMessage(
                        role="assistant",
                        content=last_assistant_text,
                        tool_calls=llm_response.tool_calls,
                    )
                )

                # If the model did not generate any tool calls, the task is finished
                if not llm_response.tool_calls:
                    break

                # STEP 4: Execute model tool calls with governance and approval checks
                for tool_call in llm_response.tool_calls:
                    tool_name = tool_call.name
                    arguments = tool_call.arguments or {}

                    # SUB-CHECK 4A: PathGuard Allowlist & Traversal Pre-Check
                    if "path" in arguments:
                        try:
                            is_write = tool_name in {"write_file", "edit_file"}
                            self.path_guard.validate(arguments["path"], allow_write=is_write)
                        except SafetyViolation as sv:
                            # Record violation and inform the agent that the action was blocked
                            self.monitor.record_violation(sv)
                            messages.append(
                                LLMMessage(
                                    role="tool",
                                    tool_call_id=tool_call.call_id,
                                    name=tool_name,
                                    content=f"[GOVERNANCE_BLOCKED] {sv.message}",
                                )
                            )
                            continue

                    # SUB-CHECK 4B: Human-In-The-Loop Approval Hook
                    approved = True
                    if self.governance.require_human_approval:
                        approved = self.approval_hook(tool_name, arguments)

                    if not approved:
                        violation = SafetyViolation(
                            violation_type=SafetyViolationType.APPROVAL_REJECTED,
                            message=f"Human operator rejected tool execution: {tool_name}",
                            tool_name=tool_name,
                        )
                        self.monitor.record_violation(violation)
                        messages.append(
                            LLMMessage(
                                role="tool",
                                tool_call_id=tool_call.call_id,
                                name=tool_name,
                                content=f"[HUMAN_REJECTED] The user denied permission to run {tool_name}.",
                            )
                        )
                        continue

                    # SUB-CHECK 4C: Dispatch to MCP Server
                    try:
                        tool_output = await client.call_tool(tool_name, arguments)
                    except Exception as exc:
                        tool_output = f"[TOOL_ERROR] Failed executing {tool_name}: {exc}"

                    # Detect if tests succeeded inside the Docker sandbox
                    if tool_name == "run_docker_tests" and "Status: PASSED" in tool_output:
                        test_passed = True

                    messages.append(
                        LLMMessage(
                            role="tool",
                            tool_call_id=tool_call.call_id,
                            name=tool_name,
                            content=tool_output,
                        )
                    )

            # Retrieve final git diff to inspect changes
            diff = await client.call_tool("git_diff", {})
            status = "SUCCESS" if (test_passed or not self.monitor.violations) else "PARTIAL"

            return AgentRunResult(
                status=status,
                summary=last_assistant_text or "Task execution complete.",
                steps_taken=self.monitor.current_step,
                prompt_tokens=self.monitor.prompt_tokens,
                completion_tokens=self.monitor.completion_tokens,
                total_tokens=self.monitor.total_tokens,
                cost_usd=round(self.monitor.cost_usd, 6),
                violations=[v.to_dict() for v in self.monitor.violations],
                test_passed=test_passed,
                git_diff=diff,
                messages=[m.to_dict() for m in messages],
            )
