"""Framework-free LLM provider interface for PatchGuard.

=============================================================================
WHY THIS MODULE EXISTS (From Scratch LLM Client & Token Tracking Concept):
Most agent tutorials rely on heavy frameworks like LangChain, AutoGen, or CrewAI.
PatchGuard deliberately implements its LLM layer from scratch using pure Python
standard library (`urllib.request`):

Key advantages:
1. No Framework Overhead: Complete transparency into what is sent and received.
2. Provider Agnostic: Uniform interface for Google Gemini, OpenAI-compatible APIs,
   and deterministic Mock models.
3. Token Governance & Pricing: Every response parses exact prompt and completion
   token counts from API metadata, mapping them to dollar rates to enforce budgets.
4. Offline Mock Provider: Enables deterministic benchmark testing and CI/CD without
   spending money or needing live internet access.
=============================================================================
"""

from __future__ import annotations

import json
import os
import urllib.error
import urllib.request
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Optional


def load_env_file(env_path: str | Path = ".env") -> None:
    """Read a .env file and populate missing keys into os.environ.

    Allows users to place GEMINI_API_KEY=... in a local .env file without
    requiring manual terminal export commands every session.
    """
    path = Path(env_path)
    if not path.is_file():
        return

    try:
        with open(path, "r", encoding="utf-8") as f:
            for line in f:
                line = line.strip()
                # Skip comments and empty lines
                if not line or line.startswith("#") or "=" not in line:
                    continue
                key, val = line.split("=", 1)
                key = key.strip()
                val = val.strip().strip("'\"")
                # Do not overwrite existing environment variables
                if key and val and key not in os.environ:
                    os.environ[key] = val
    except Exception:
        pass


# Automatically attempt to load local .env on import
load_env_file()


@dataclass
class ToolCall:
    """Represents a structured function call request generated by the LLM.

    Attributes:
        call_id: Unique identifier for this call (e.g. 'call_abc123').
        name: Name of the target tool (e.g. 'read_file').
        arguments: Parsed JSON dictionary of arguments passed by the model.
    """

    call_id: str
    name: str
    arguments: dict[str, Any]

    def to_dict(self) -> dict[str, Any]:
        """Convert to standard OpenAI/Gemini tool_call format."""
        return {
            "id": self.call_id,
            "type": "function",
            "function": {
                "name": self.name,
                "arguments": json.dumps(self.arguments),
            },
        }


@dataclass
class LLMMessage:
    """A single chat message in the conversation history.

    Roles supported:
    - 'system': Guardrails, behavior instructions, and persona.
    - 'user': The user prompt, task description, or issue report.
    - 'assistant': Thoughts and tool call requests from the model.
    - 'tool': The output text returned after executing a tool.
    """

    role: str
    content: str
    name: Optional[str] = None
    tool_call_id: Optional[str] = None
    tool_calls: list[ToolCall] = field(default_factory=list)

    def to_dict(self) -> dict[str, Any]:
        """Serialize message to API-compatible JSON format."""
        data: dict[str, Any] = {"role": self.role, "content": self.content}
        if self.name:
            data["name"] = self.name
        if self.tool_call_id:
            data["tool_call_id"] = self.tool_call_id
        if self.tool_calls:
            data["tool_calls"] = [tc.to_dict() for tc in self.tool_calls]
        return data


@dataclass
class LLMResponse:
    """Model response package including text, tool calls, and token usage."""

    content: str
    tool_calls: list[ToolCall] = field(default_factory=list)
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    cost_usd: float = 0.0


# Published pricing rates per 1,000,000 tokens: (input_price_usd, output_price_usd)
MODEL_PRICING: dict[str, tuple[float, float]] = {
    "gpt-4o": (2.50, 10.00),
    "gpt-4o-mini": (0.15, 0.60),
    "claude-3-5-sonnet": (3.00, 15.00),
    "claude-3-5-haiku": (0.80, 4.00),
    "gemini-2.5-flash": (0.075, 0.30),
    "gemini-2.0-flash": (0.075, 0.30),
    "gemini-1.5-pro": (1.25, 5.00),
    "gemini-1.5-flash": (0.075, 0.30),
    "mock": (0.50, 1.50),
}


def calculate_cost(model_name: str, prompt_tokens: int, completion_tokens: int) -> float:
    """Calculate the exact dollar cost for a query based on token counts."""
    pricing = MODEL_PRICING.get(model_name, MODEL_PRICING["gemini-1.5-flash"])
    input_rate, output_rate = pricing
    cost = (prompt_tokens / 1_000_000 * input_rate) + (completion_tokens / 1_000_000 * output_rate)
    return round(cost, 6)


def estimate_tokens(text: str) -> int:
    """Lightweight fallback heuristic: ~4 characters per token in English text."""
    return max(1, len(text) // 4)


class BaseLLMProvider(ABC):
    """Abstract base class establishing the contract for all LLM providers."""

    def __init__(self, model: str = "mock") -> None:
        self.model = model

    @abstractmethod
    def complete(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.2,
    ) -> LLMResponse:
        """Send message history and tools to the LLM and return structured response."""
        pass


class OpenAICompatibleProvider(BaseLLMProvider):
    """Direct HTTP client for OpenAI-compatible endpoints using pure standard library.

    Supports OpenAI, OpenRouter, Groq, Ollama, vLLM, and any compliant endpoint.
    """

    def __init__(
        self,
        api_key: str | None = None,
        model: str = "gpt-4o-mini",
        base_url: str = "https://api.openai.com/v1",
    ) -> None:
        super().__init__(model=model)
        self.api_key = api_key or os.environ.get("OPENAI_API_KEY", "")
        self.base_url = (base_url or os.environ.get("OPENAI_BASE_URL", "https://api.openai.com/v1")).rstrip("/")

    def complete(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.2,
    ) -> LLMResponse:
        url = f"{self.base_url}/chat/completions"

        formatted_messages = [m.to_dict() for m in messages]
        payload: dict[str, Any] = {
            "model": self.model,
            "messages": formatted_messages,
            "temperature": temperature,
        }

        # Convert MCP tools into OpenAI function declaration format
        if tools:
            formatted_tools = []
            for t in tools:
                formatted_tools.append(
                    {
                        "type": "function",
                        "function": {
                            "name": t["name"],
                            "description": t.get("description", ""),
                            "parameters": t.get("input_schema", {"type": "object", "properties": {}}),
                        },
                    }
                )
            payload["tools"] = formatted_tools
            payload["tool_choice"] = "auto"

        headers = {
            "Content-Type": "application/json",
            "Authorization": f"Bearer {self.api_key}",
        }

        req = urllib.request.Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers=headers,
            method="POST",
        )

        try:
            with urllib.request.urlopen(req, timeout=45) as resp:
                data = json.loads(resp.read().decode("utf-8"))
        except urllib.error.HTTPError as exc:
            err_body = exc.read().decode("utf-8", errors="replace")
            raise RuntimeError(f"LLM API Error ({exc.code}): {err_body}") from exc

        choice = data["choices"][0]["message"]
        content = choice.get("content") or ""
        tool_calls: list[ToolCall] = []

        # Parse function calls if the model requested any tool executions
        if "tool_calls" in choice and choice["tool_calls"]:
            for raw_tc in choice["tool_calls"]:
                call_id = raw_tc.get("id", "call_1")
                func = raw_tc.get("function", {})
                name = func.get("name", "")
                raw_args = func.get("arguments", "{}")
                try:
                    arguments = json.loads(raw_args) if isinstance(raw_args, str) else raw_args
                except Exception:
                    arguments = {}
                tool_calls.append(ToolCall(call_id=call_id, name=name, arguments=arguments))

        # Extract token usage metadata from API response
        usage = data.get("usage", {})
        prompt_tokens = usage.get("prompt_tokens", estimate_tokens(str(messages)))
        completion_tokens = usage.get("completion_tokens", estimate_tokens(content))
        total_tokens = usage.get("total_tokens", prompt_tokens + completion_tokens)
        cost = calculate_cost(self.model, prompt_tokens, completion_tokens)

        return LLMResponse(
            content=content,
            tool_calls=tool_calls,
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            cost_usd=cost,
        )


class GeminiProvider(OpenAICompatibleProvider):
    """Direct HTTP client for Google Gemini API via its OpenAI-compatible endpoint.

    How it connects:
    Google provides an OpenAI-compatible endpoint at:
    `https://generativelanguage.googleapis.com/v1beta/openai/chat/completions`

    By subclassing OpenAICompatibleProvider and passing Google's endpoint,
    PatchGuard gains full Gemini capability (tool calling, streaming, role messages)
    without installing heavy third-party SDKs!
    """

    def __init__(
        self,
        api_key: str | None = None,
        model: str = "gemini-1.5-flash",
    ) -> None:
        key = api_key or os.environ.get("GEMINI_API_KEY") or os.environ.get("GOOGLE_API_KEY", "")
        if not key:
            raise ValueError(
                "Missing Gemini API key. Please set GEMINI_API_KEY in your environment or in a .env file."
            )
        super().__init__(
            api_key=key,
            model=model,
            base_url="https://generativelanguage.googleapis.com/v1beta/openai",
        )


class MockLLMProvider(BaseLLMProvider):
    """Deterministic or scripted LLM provider for fast, cost-free testing and benchmarks.

    Allows unit tests and evaluation suites to simulate agent reasoning, tool execution,
    and attack vectors without needing an active internet connection or paid API keys.
    """

    def __init__(
        self,
        scripted_responses: list[LLMResponse] | None = None,
        generator: Optional[Callable[[list[LLMMessage], list[dict[str, Any]] | None], LLMResponse]] = None,
        model: str = "mock",
    ) -> None:
        super().__init__(model=model)
        self.scripted_responses = list(scripted_responses or [])
        self.generator = generator
        self.call_history: list[list[LLMMessage]] = []

    def complete(
        self,
        messages: list[LLMMessage],
        tools: list[dict[str, Any]] | None = None,
        temperature: float = 0.2,
    ) -> LLMResponse:
        self.call_history.append(messages)

        # 1. Use pre-scripted sequential response if provided
        if self.scripted_responses:
            return self.scripted_responses.pop(0)

        # 2. Use custom callback generator if provided
        if self.generator:
            return self.generator(messages, tools)

        # 3. Default fallback behavior: simulate running tests then summarizing
        last_msg = messages[-1] if messages else LLMMessage(role="user", content="")
        prompt_text = " ".join([m.content for m in messages if m.content])
        p_toks = estimate_tokens(prompt_text)

        # If previous step was a tool output, conclude
        if last_msg.role == "tool":
            c_toks = 40
            return LLMResponse(
                content="I have reviewed the diagnostic tool outputs. The root cause has been identified and verified.",
                tool_calls=[],
                prompt_tokens=p_toks,
                completion_tokens=c_toks,
                total_tokens=p_toks + c_toks,
                cost_usd=calculate_cost(self.model, p_toks, c_toks),
            )

        # First step: diagnose by running tests
        c_toks = 30
        tc = ToolCall(call_id="call_mock_1", name="run_docker_tests", arguments={"test_command": "pytest"})
        return LLMResponse(
            content="Let me first run the test suite inside the Docker sandbox to diagnose the issue.",
            tool_calls=[tc],
            prompt_tokens=p_toks,
            completion_tokens=c_toks,
            total_tokens=p_toks + c_toks,
            cost_usd=calculate_cost(self.model, p_toks, c_toks),
        )
